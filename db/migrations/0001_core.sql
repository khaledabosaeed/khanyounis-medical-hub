CREATE TABLE IF NOT EXISTS students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(254) NOT NULL,
  email_normalized VARCHAR(254) NOT NULL,
  phone VARCHAR(32) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  CONSTRAINT uq_students_email_normalized UNIQUE (email_normalized)
);

CREATE TABLE IF NOT EXISTS study_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  started_at TIMESTAMPTZ(3) NOT NULL,
  ended_at TIMESTAMPTZ(3) NULL,
  duration_seconds BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  CONSTRAINT fk_study_sessions_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_study_sessions_student_started ON study_sessions (student_id, started_at);
CREATE INDEX IF NOT EXISTS idx_study_sessions_status_started ON study_sessions (status, started_at);

CREATE TABLE IF NOT EXISTS student_auth_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  student_id BIGINT NOT NULL,
  current_study_session_id BIGINT NULL,
  csrf_token VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  expires_at TIMESTAMPTZ(3) NOT NULL,
  CONSTRAINT fk_student_auth_sessions_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
  CONSTRAINT fk_student_auth_sessions_study FOREIGN KEY (current_study_session_id) REFERENCES study_sessions(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_student_auth_sessions_student ON student_auth_sessions (student_id);
CREATE INDEX IF NOT EXISTS idx_student_auth_sessions_expiry ON student_auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  open_id VARCHAR(191) NOT NULL,
  email VARCHAR(254) NOT NULL,
  email_normalized VARCHAR(254) NOT NULL,
  full_name VARCHAR(160) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  last_login_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  CONSTRAINT uq_admins_open_id UNIQUE (open_id),
  CONSTRAINT uq_admins_email_normalized UNIQUE (email_normalized)
);

CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  read_at TIMESTAMPTZ(3) NULL,
  created_by_admin_open_id VARCHAR(191) NOT NULL,
  CONSTRAINT fk_messages_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_messages_student_created ON messages (student_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_unread ON messages (student_id, read_at);
