CREATE TABLE IF NOT EXISTS admin_login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_normalized VARCHAR(254) NOT NULL,
  source_hash CHAR(64) NOT NULL,
  attempted_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_admin_login_attempts_window ON admin_login_attempts (email_normalized, source_hash, attempted_at);
