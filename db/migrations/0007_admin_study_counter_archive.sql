CREATE TABLE IF NOT EXISTS admin_study_counter_archive (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_started_at TIMESTAMPTZ(3) NULL,
  period_ended_at TIMESTAMPTZ(3) NOT NULL,
  completed_session_count BIGINT NOT NULL DEFAULT 0,
  total_seconds BIGINT NOT NULL DEFAULT 0,
  archived_by_admin_id BIGINT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
  CONSTRAINT fk_counter_archive_admin FOREIGN KEY (archived_by_admin_id) REFERENCES admins(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_counter_archive_period ON admin_study_counter_archive (period_ended_at);
